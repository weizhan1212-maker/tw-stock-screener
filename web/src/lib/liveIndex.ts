/** 台指期盤後交易時段（15:00–隔天 05:00，台灣時間），用來決定要不要繼續更新 */
export function inNightSession(d = new Date()) {
  const p = Object.fromEntries(
    new Intl.DateTimeFormat("en-US", { timeZone: "Asia/Taipei", weekday: "short", hour: "2-digit", minute: "2-digit", hour12: false })
      .formatToParts(d).map((x) => [x.type, x.value]),
  );
  const m = Number(p.hour) % 24 * 60 + Number(p.minute);
  const wd = p.weekday;
  if (m >= 15 * 60) return !["Sat", "Sun"].includes(wd);              // 週一到週五 15:00 後
  if (m < 5 * 60) return !["Sun", "Mon"].includes(wd);               // 週二到週六清晨（前一晚延續）
  return false;
}
